Mat3Fix Mat3Fix::createRotation(uint8_t azimuth, uint8_t elevation) {
  Mat3Fix res;
  fixed_t sa = fix_sin(azimuth);
  fixed_t ca = fix_cos(azimuth);
  fixed_t se = fix_sin(elevation);
  fixed_t ce = fix_cos(elevation);

  // カメラ視線空間:
  // Xcam: スクリーン右方向 = -sa*X + ca*Y
  // Ycam: スクリーン上方向 = -se*ca*X - se*sa*Y + ce*Z
  // Zcam: スクリーン奥（視線深度）方向 = ce*ca*X + ce*sa*Y + se*Z

  res.m[0][0] = -sa;
  res.m[0][1] = ca;
  res.m[0][2] = 0;

  res.m[1][0] = -fix_mul(se, ca);
  res.m[1][1] = -fix_mul(se, sa);
  res.m[1][2] = ce;

  res.m[2][0] = fix_mul(ce, ca);
  res.m[2][1] = fix_mul(ce, sa);
  res.m[2][2] = se;

  return res;
}

